#!/usr/bin/env python3
"""
Builds src/sim/data/districts.ts: 2024 presidential and House results for all 435
districts (2024 lines), from github.com/jaytimm/PresElectionResults (data-raw/):
  - "2024 Pres by CD - Main.csv"  (The Downballot / state sources via that repo)
  - "1976-2024-house.tab"          (MIT Election Data and Science Lab)
NY-21 is blank in the source and is filled with an estimate.
Mid-decade redistricting for 2026 (TX, CA, MO, NC, OH, UT) is not reflected.

Usage:
  git clone --depth 1 https://github.com/jaytimm/PresElectionResults /tmp/per
  python3 scripts/build_districts.py /tmp/per/data-raw
"""
import collections, csv, json, sys
from pathlib import Path

def main(raw):
    raw = Path(raw)
    num = lambda x: int(x.replace(",", "")) if x.strip() else 0
    pres, est, tot = {}, [], collections.defaultdict(lambda: [0, 0])
    for r in csv.DictReader(open(raw / "2024 Pres by CD - Main.csv")):
        st, d = r["CD"].split("-"); d = 0 if d == "AL" else int(d)
        h, t = num(r["Harris"]), num(r["Trump"])
        if h + t == 0:
            pres[(st, d)] = 0.395; est.append(f"{st}-{d}"); h, t = 150000, 230000
        else:
            pres[(st, d)] = h / (h + t)
        tot[st][0] += h; tot[st][1] += t
    house = {}
    for r in csv.DictReader(open(raw / "1976-2024-house.tab")):
        if r["year"] != "2024" or r["stage"] != "GEN" or r["special"] == "TRUE":
            continue
        k = (r["state_po"], int(r["district"]) if r["district"] not in ("0", "") else 0)
        h = house.setdefault(k, {"D": 0, "R": 0, "win": "", "wv": 0})
        v = int(r["candidatevotes"] or 0); p = r["party"] or ""
        if p.startswith("DEMOCRAT"): h["D"] += v
        elif p == "REPUBLICAN": h["R"] += v
        if v > h["wv"]: h["wv"], h["win"] = v, r["candidate"]
    rows = []
    for (st, d), ps in sorted(pres.items()):
        h = house.get((st, d))
        hd = round(h["D"] / (h["D"] + h["R"]), 4) if h and h["D"] and h["R"] else None
        rows.append([st, d, round(ps, 4), hd, (h or {}).get("win", "")])
    nat = sum(v[0] for v in tot.values()) / sum(sum(v) for v in tot.values())
    out = Path(__file__).resolve().parent.parent / "src" / "sim" / "data" / "districts.ts"
    with open(out, "w") as f:
        f.write("// Generated by scripts/build_districts.py. 2024 results on 2024 district lines.\n")
        f.write("// [state, district, Harris two-party share, Democratic two-party House share (null if uncontested), 2024 House winner]\n")
        f.write("export const DISTRICTS_2024: [string, number, number, number | null, string][] = " + json.dumps(rows, ensure_ascii=False) + ";\n\n")
        f.write("/** Harris two-party share by state, 2024. */\n")
        f.write("export const STATE_PRES_2024: Record<string, number> = " + json.dumps({k: round(v[0] / sum(v), 4) for k, v in tot.items()}) + ";\n\n")
        f.write(f"export const NATIONAL_PRES_2024 = {round(nat, 4)};\n")
        f.write(f"export const ESTIMATED_DISTRICTS = {json.dumps(est)};\n")
    print(f"{len(rows)} districts, national {nat:.4f}, estimated {est} -> {out}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/per/data-raw")
