#!/usr/bin/env python3
"""
Build real pops from the Census Bureau's ACS PUMS (Public Use Microdata Sample).

The game ships with approximate pops raked from hand-typed state figures. This
script swaps them for the real thing: every person record in the ACS, weighted
by PWGTP, grouped into state x culture x job.

1. Download the person files (one CSV per state, or the all-states file) from
   https://www.census.gov/programs-surveys/acs/microdata/access.html
   (e.g. the 2023 1-year or 2019-2023 5-year "csv_pus.zip"), or make an extract
   at https://usa.ipums.org with the same variables. Unzip them into data/raw/.
2. Run:  python3 scripts/pums_to_pops.py data/raw/psam_p*.csv
3. It writes src/sim/data/popsOverride.ts. Rebuild the game and the real pops
   are used instead of the approximate ones.

Variables used: ST, PWGTP, ESR, HISP, RAC1P, RAC2P, OCCP.
Code lists change between survey years. Check RAC2P_ASIAN and the OCCP ranges
below against the PUMS data dictionary for the year you download.
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

FIPS_TO_CODE = {
    "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC",
    "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
    "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT",
    "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
    "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT",
    "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY",
}

# Detailed Asian race codes (RAC2P, 2019+ dictionaries). VERIFY for your survey year.
RAC2P_ASIAN = {
    "38": "indian", "43": "chinese", "44": "chinese", "45": "filipino", "49": "korean", "57": "vietnamese",
}

# OCCP (2018+ census occupation codes) -> game job. Ranges are inclusive.
OCCP_RANGES = [
    (10, 440, "manager"),
    (500, 960, "professional"),     # business & financial operations
    (1005, 1240, "software"),       # computer & mathematical
    (1305, 1460, "engineer"),       # architects & engineers
    (1520, 1560, "technician"),     # drafters, engineering technicians
    (1600, 1860, "scientist"),      # life, physical & social scientists
    (1900, 1980, "technician"),     # science technicians
    (2001, 2970, "professional"),   # social services, legal, education, arts & media
    (3000, 3270, "professional"),   # healthcare practitioners
    (3300, 3550, "technician"),     # health technologists
    (3601, 4655, "service"),        # healthcare support, protective, food, cleaning, personal care
    (4700, 4760, "service"),        # retail sales
    (4800, 4965, "clerk"),          # sales reps & related
    (5000, 5940, "clerk"),          # office & administrative support
    (6005, 6130, "laborer"),        # farming, fishing, forestry
    (6200, 6950, "laborer"),        # construction & extraction
    (7000, 7640, "technician"),     # installation, maintenance & repair
    (7700, 8990, "laborer"),        # production
    (9005, 9760, "laborer"),        # transportation & material moving
]


def job_of(occp: str):
    try:
        code = int(occp)
    except ValueError:
        return None
    for lo, hi, job in OCCP_RANGES:
        if lo <= code <= hi:
            return job
    return None  # military or unemployed with no occupation


def culture_of(row):
    hisp = row.get("HISP", "01").zfill(2)
    if hisp != "01":
        return "mexican" if hisp == "02" else "latino"
    rac1p = row.get("RAC1P", "")
    if rac1p == "1":
        return "white"
    if rac1p == "2":
        return "black"
    if rac1p in ("3", "4", "5", "7"):
        return "native"
    if rac1p == "6":
        return RAC2P_ASIAN.get(row.get("RAC2P", "").lstrip("0").zfill(2), "asian_other")
    return "multiracial"


def main(paths):
    totals = defaultdict(float)
    people = 0
    for path in paths:
        with open(path, newline="") as f:
            for row in csv.DictReader(f):
                if row.get("ESR", "") not in ("1", "2", "3", "4", "5"):
                    continue  # not in the labor force
                st = FIPS_TO_CODE.get(row["ST"].zfill(2))
                job = job_of(row.get("OCCP", ""))
                if not st or not job:
                    continue
                totals[(st, culture_of(row), job)] += float(row["PWGTP"])
                people += 1
        print(f"read {path}", file=sys.stderr)
    rows = sorted((k[0], k[1], k[2], round(v)) for k, v in totals.items() if v >= 100)
    out = Path(__file__).resolve().parent.parent / "src" / "sim" / "data" / "popsOverride.ts"
    with open(out, "w") as f:
        f.write("// Generated by scripts/pums_to_pops.py from ACS PUMS person records. Do not edit by hand.\n")
        f.write("// [state, culture, job, workers]\n")
        f.write("export const POPS_OVERRIDE: [string, string, string, number][] | null = [\n")
        for st, cu, job, n in rows:
            f.write(f'  ["{st}", "{cu}", "{job}", {n}],\n')
        f.write("];\n")
    print(f"{people:,} person records -> {len(rows):,} pops, {sum(r[3] for r in rows):,} workers -> {out}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1:])
