def main(path):
    wb = openpyxl.load_workbook(path, read_only=True)
    out = {"m": {}, "f": {}, "last": {}}
    for sheet, key, cap in (("First names", "m", FIRST_CAP), ("Last names", "last", LAST_CAP)):
        rows = list(wb[sheet].iter_rows(values_only=True))
        head = rows[0]
        for i, h in enumerate(head):
            if h in COLS:
                vals = [str(r[i]).strip() for r in rows[1:] if r[i]]
                out[key][COLS[h]] = vals[:cap]
    for country, bg, _w, kind, name in list(wb["International"].iter_rows(values_only=True))[1:]:
        if country in INTL and name:
            out["m" if kind == "First" else "last"].setdefault(INTL[country], []).append(str(name).strip())
    for k, v in WOMEN.items():
        seen = []
        for n in v.split():
            if n not in seen: seen.append(n)
        out["f"][k] = seen
    lines = ["// Generated by scripts/build_names.py. Men's first names and last names: the Football Coach / College Manager",
             "// name pools, ordered most common first. Women's first names are typed in by hand in the script.",
             "// Each list is one string joined with '|' to keep the bundle small.",
             "export type NamePool = Record<string, string>;"]
    for k in ("m", "f", "last"):
        obj = {bg: "|".join(v) for bg, v in out[k].items()}
        lines.append(f"export const {dict(m='MEN', f='WOMEN', last='LAST')[k]}: NamePool = {json.dumps(obj, ensure_ascii=False)};")
    open("src/sim/data/names.ts", "w").write("\n".join(lines) + "\n")
    for k in out: print(k, {bg: len(v) for bg, v in out[k].items()})

main(sys.argv[1])
