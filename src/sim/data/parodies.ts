function seed(p: P): CompanySeed {
  const produce: ProductionSeed[] = p.lines.map(([good, rev, states, method]) => ({ good, annualRevenue: rev, states, ...(method ? { method } : {}) }));
  const brand: Partial<Record<GoodId, number>> = {}, priceMult: Partial<Record<GoodId, number>> = {};
  for (const [g] of p.lines) { brand[g] = p.brand ?? 1.6; priceMult[g] = p.price ?? 1.05; }
  return {
    key: p.key, name: p.name, ticker: p.ticker, color: p.color, inspiredBy: p.inspiredBy, tagline: p.tagline, hq: p.hq,
    marketCap: p.mcap, cash: p.mcap * 0.05, debt: p.debt ?? p.mcap * 0.12, shares: p.mcap / 180,
    priceMult, brand, techEdge: p.tech ?? {}, produce, rndIntensity: p.rnd ?? 0.01, rndStates: { [p.hq]: 1 },
    marketingPct: p.mkt ?? 0.03, wagePolicy: p.wage ?? 1, tier: p.tier ?? "incumbent",
  };
}

